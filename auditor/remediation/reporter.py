"""Report generator - produces JSON and Markdown remediation reports."""

from __future__ import annotations

import json
from pathlib import Path
from typing import List

from auditor.remediation.models import (
    PatchProposal,
    PatchStatus,
    PatchValidationResult,
    RemediationReport,
)


def _status_emoji(status: PatchStatus) -> str:
    return {
        PatchStatus.VALIDATED: "[VALIDATED]",
        PatchStatus.PROPOSED: "[PROPOSED]",
        PatchStatus.REQUIRES_REVIEW: "[REVIEW]",
        PatchStatus.VALIDATION_FAILED: "[FAILED]",
        PatchStatus.VALIDATION_INCOMPLETE: "[INCOMPLETE]",
        PatchStatus.REJECTED: "[REJECTED]",
        PatchStatus.APPLIED_IN_ISOLATION: "[ISOLATED]",
        PatchStatus.UNSUPPORTED: "[UNSUPPORTED]",
    }.get(status, "[?]")


def save_json_report(report: RemediationReport, output_dir: Path) -> Path:
    output_dir.mkdir(parents=True, exist_ok=True)
    out = output_dir / "remediation-report.json"
    out.write_text(report.model_dump_json(indent=2), encoding="utf-8")
    return out


def save_markdown_report(report: RemediationReport, output_dir: Path) -> Path:
    output_dir.mkdir(parents=True, exist_ok=True)
    out = output_dir / "remediation-report.md"
    lines = [
        f"# Remediation Report",
        f"",
        f"**Scan ID:** `{report.scan_id}`  ",
        f"**Target:** `{report.target}`  ",
        f"**Generated:** {report.timestamp}",
        f"",
        f"---",
        f"",
        f"## Summary",
        f"",
        f"| | Count |",
        f"|---|---|",
        f"| Total proposals | {len(report.proposals)} |",
        f"| Unsupported findings | {len(report.unsupported_finding_ids)} |",
        f"| Validation results | {len(report.validation_results)} |",
        f"",
    ]

    if report.proposals:
        lines += ["## Proposals", ""]
        for p in report.proposals:
            emoji = _status_emoji(p.status)
            lines += [
                f"### {emoji} `{p.patch_id}` - Finding `{p.finding_id}`",
                f"",
                f"- **Strategy:** `{p.strategy.value}`",
                f"- **Status:** `{p.status.value}`",
                f"- **Target file:** `{p.target_file or 'N/A'}`",
                f"- **Generated by:** {p.generated_by}",
                f"- **Timestamp:** {p.timestamp}",
                f"",
                f"**Explanation:** {p.explanation}",
                f"",
            ]
            if p.warnings:
                lines += ["**[WARN] Warnings:**", ""]
                for w in p.warnings:
                    lines.append(f"- {w}")
                lines.append("")
            if p.unified_diff:
                lines += [
                    "**Proposed diff:**",
                    "```diff",
                    p.unified_diff[:4000],
                    "```",
                    "",
                ]
            lines.append("---")
            lines.append("")

    if report.validation_results:
        lines += ["## Validation Results", ""]
        for vr in report.validation_results:
            emoji = _status_emoji(vr.overall_status)
            lines += [
                f"### {emoji} Patch `{vr.patch_id}`",
                f"",
                f"- **Overall status:** `{vr.overall_status.value}`",
                f"- **Human review required:** {'Yes' if vr.requires_human_review else 'No'}",
                f"- **Security re-analysis cleared:** {vr.security_reanalysis_cleared}",
                f"- **Regression detected:** {vr.regression_detected}",
                f"",
                f"| Check | Status | Detail |",
                f"|---|---|---|",
            ]
            for c in vr.checks:
                detail = c.detail.replace("|", "\\|")[:120]
                lines.append(f"| `{c.check_name}` | `{c.status.value}` | {detail} |")
            if vr.failure_reason:
                lines += ["", f"**Failure reason:** {vr.failure_reason}"]
            lines += ["", "---", ""]

    if report.unsupported_finding_ids:
        lines += [
            "## Unsupported Findings",
            "",
            "The following findings have no automated remediation strategy:",
            "",
        ]
        for fid in report.unsupported_finding_ids:
            lines.append(f"- `{fid}`")
        lines.append("")

    if report.warnings:
        lines += ["## Report Warnings", ""]
        for w in report.warnings:
            lines.append(f"- {w}")
        lines.append("")

    out.write_text("\n".join(lines), encoding="utf-8")
    return out


def save_patch_files(proposals: List[PatchProposal], output_dir: Path) -> None:
    """Save individual patch .diff and .json files."""
    patches_dir = output_dir / "patches"
    patches_dir.mkdir(parents=True, exist_ok=True)

    for p in proposals:
        if p.unified_diff:
            diff_path = patches_dir / f"{p.patch_id}.diff"
            diff_path.write_text(p.unified_diff, encoding="utf-8")

        # Save metadata JSON (no original_content to keep files small)
        meta = p.model_dump()
        meta.pop("original_content", None)
        meta.pop("proposed_content", None)
        json_path = patches_dir / f"{p.patch_id}.json"
        json_path.write_text(json.dumps(meta, indent=2), encoding="utf-8")


"""Save evaluation reports in JSON and Markdown formats."""

from __future__ import annotations

import json
from pathlib import Path
from typing import Optional

from auditor.evaluation.models import DetectionMetrics, EvaluationRun


def save_evaluation_json(run: EvaluationRun, output_dir: Path) -> Path:
    """Serialize the full EvaluationRun to a JSON report file."""
    output_dir = Path(output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)
    out_path = output_dir / f"evaluation_{run.run_id}.json"
    out_path.write_text(
        run.model_dump_json(indent=2),
        encoding="utf-8",
    )
    return out_path


def _metrics_table(m: DetectionMetrics) -> str:
    """Format a DetectionMetrics object as a markdown table row."""
    precision = f"{m.precision:.4f}" if m.precision is not None else "N/A"
    recall = f"{m.recall:.4f}" if m.recall is not None else "N/A"
    f1 = f"{m.f1:.4f}" if m.f1 is not None else "N/A"
    accuracy = f"{m.accuracy:.4f}" if m.accuracy is not None else "N/A"
    return (
        f"| TP={m.tp} | FP={m.fp} | TN={m.tn} | FN={m.fn} | "
        f"Precision={precision} | Recall={recall} | F1={f1} | Accuracy={accuracy} |"
    )


def save_evaluation_markdown(run: EvaluationRun, output_dir: Path) -> Path:
    """Generate a human-readable Markdown evaluation report."""
    output_dir = Path(output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)
    out_path = output_dir / f"evaluation_{run.run_id}.md"

    lines = [
        "# SYNTAXIS Evaluation Report",
        "",
        f"**Run ID:** `{run.run_id}`  ",
        f"**Timestamp:** {run.timestamp}  ",
        f"**Dataset:** {run.dataset_id} v{run.dataset_version}  ",
        f"**Dataset Hash (SHA-256):** `{run.dataset_hash}`  ",
        f"**Offline:** {run.offline}  **No-LLM:** {run.no_llm}",
        "",
        "---",
        "",
        "## Summary",
        "",
        f"- Cases total: **{run.cases_total}**",
        f"- Cases completed: **{run.cases_completed}**",
        f"- {run.summary}",
        "",
        "---",
        "",
        "## Overall Detection Metrics",
        "",
        "| Metric | Value |",
        "|--------|-------|",
        f"| True Positives (TP) | {run.overall_metrics.tp} |",
        f"| False Positives (FP) | {run.overall_metrics.fp} |",
        f"| True Negatives (TN) | {run.overall_metrics.tn} |",
        f"| False Negatives (FN) | {run.overall_metrics.fn} |",
        f"| Ambiguous | {run.overall_metrics.ambiguous} |",
        f"| Errors | {run.overall_metrics.errors} |",
        f"| Precision | {run.overall_metrics.precision} |",
        f"| Recall | {run.overall_metrics.recall} |",
        f"| F1 Score | {run.overall_metrics.f1} |",
        f"| Accuracy | {run.overall_metrics.accuracy} |",
        "",
        "---",
        "",
        "## Per-Category Metrics",
        "",
        "| Category | TP | FP | TN | FN | Precision | Recall | F1 | Accuracy |",
        "|----------|----|----|----|----|-----------|--------|-----|----------|",
    ]

    for cat, m in sorted(run.per_category.items()):
        prec = f"{m.precision:.4f}" if m.precision is not None else "N/A"
        rec = f"{m.recall:.4f}" if m.recall is not None else "N/A"
        f1 = f"{m.f1:.4f}" if m.f1 is not None else "N/A"
        acc = f"{m.accuracy:.4f}" if m.accuracy is not None else "N/A"
        lines.append(
            f"| {cat} | {m.tp} | {m.fp} | {m.tn} | {m.fn} | {prec} | {rec} | {f1} | {acc} |"
        )

    lines += [
        "",
        "---",
        "",
        "## Performance",
        "",
        f"- Total cases: {run.performance.get('total_cases', 'N/A')}",
        f"- Total time: {run.performance.get('total_seconds', 'N/A')}s",
        f"- Mean time/case: {run.performance.get('mean_seconds', 'N/A')}s",
        f"- Median time/case: {run.performance.get('median_seconds', 'N/A')}s",
        f"- Min: {run.performance.get('min_seconds', 'N/A')}s  Max: {run.performance.get('max_seconds', 'N/A')}s",
        "",
        "---",
        "",
        "## Case Results",
        "",
        "| ID | Category | Label | Status | Findings | CWE Matched | Duration (s) |",
        "|----|----------|-------|--------|----------|-------------|-------------|",
    ]

    for r in run.case_results:
        lines.append(
            f"| {r.case_id} | {r.category} | {r.label} | **{r.status.upper()}** "
            f"| {r.findings_count} | {r.matched_cwe} | {r.duration_seconds:.3f} |"
        )

    if run.warnings:
        lines += [
            "",
            "---",
            "",
            "## Warnings",
            "",
        ]
        for w in run.warnings:
            lines.append(f"- {w}")

    lines += [
        "",
        "---",
        "",
        "*Generated by SYNTAXIS Phase F evaluation framework.*",
    ]

    out_path.write_text("\n".join(lines), encoding="utf-8")
    return out_path

